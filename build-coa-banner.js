#!/usr/bin/env node
/**
 * Builds preview/coa-banner-preview.html from wordpress/product-coa-banner.php.
 *
 * The product list and the stylesheet are both parsed out of the PHP snippet, so
 * the preview cannot drift from what the site will actually render. If the parse
 * finds nothing, the build fails rather than emitting a silently empty preview.
 */
const fs = require('fs');
const path = require('path');

const dir = f => path.join(__dirname, f);
const php = fs.readFileSync(dir('wordpress/product-coa-banner.php'), 'utf8');

// Product rows: 'SKU' => array( 'label' => '...', 'id' => N ),
const rowRe = /'([A-Z0-9-]+)'\s*=>\s*array\(\s*'label'\s*=>\s*'([^']+)'\s*,\s*'id'\s*=>\s*(\d+)/g;
const products = [];
let m;
while ((m = rowRe.exec(php)) !== null) {
  products.push({ sku: m[1], label: m[2], id: Number(m[3]) });
}
if (products.length === 0) {
  throw new Error('Parsed zero products from product-coa-banner.php — check the array format.');
}

const styleMatch = php.match(/<style id="opl-coa-banner-styles">([\s\S]*?)<\/style>/);
if (!styleMatch) {
  throw new Error('Could not find the opl-coa-banner-styles block in product-coa-banner.php.');
}
const css = styleMatch[1];

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const DOCS = 'https://www.oligopolypeptides.com/research-peptides-with-coa/';

const banner = p => `      <a class="opl-coa-banner" href="${DOCS}"
         aria-label="Certificate of Analysis available for ${esc(p.label)} — view documentation">
        <span class="opl-coa-banner__badge">COA Available</span>
        <span class="opl-coa-banner__text">Certificate of Analysis on file</span>
        <span class="opl-coa-banner__cta" aria-hidden="true">View&nbsp;COA&nbsp;&rarr;</span>
      </a>`;

const cards = products.map(p => `    <article class="pv-card">
      <h1 class="pv-title">${esc(p.label)}</h1>
${banner(p)}
      <p class="pv-price">$—</p>
      <p class="pv-meta">SKU ${esc(p.sku)} &middot; product ID ${p.id}</p>
    </article>`).join('\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>COA banner preview — OligoPoly product pages</title>
<style>
/* ---- preview chrome only (pv-), approximating the product page ---- */
body{margin:0;padding:28px 18px 48px;background:#030712;color:#e2e8f0;
  font-family:Inter,system-ui,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif;}
.pv-wrap{max-width:760px;margin:0 auto;}
.pv-head{margin:0 0 6px;font-size:19px;font-weight:750;color:#f8fafc;}
.pv-sub{margin:0 0 26px;font-size:13px;color:#94a3b8;line-height:1.6;}
.pv-sub code{color:#d8b4fe;}
.pv-card{margin:0 0 16px;padding:18px 20px;border:1px solid rgba(148,163,184,.18);
  border-radius:10px;background:linear-gradient(145deg,rgba(10,8,22,.97),rgba(5,13,24,.98));}
.pv-title{margin:0 0 2px;font-size:22px;font-weight:750;color:#f8fafc;line-height:1.25;}
.pv-price{margin:6px 0 2px;font-size:18px;font-weight:700;color:#f8fafc;}
.pv-meta{margin:0;font-size:11.5px;color:#64748b;letter-spacing:.02em;}

/* ---- banner styles, parsed verbatim from wordpress/product-coa-banner.php ---- */
${css.trim()}
</style>
</head>
<body>
  <div class="pv-wrap">
    <h1 class="pv-head">COA banner — preview</h1>
    <p class="pv-sub">Generated from <code>wordpress/product-coa-banner.php</code> by
      <code>node build-coa-banner.js</code>. The banner renders between the product
      title and the price (<code>woocommerce_single_product_summary</code>, priority 6).
      ${products.length} products. Do not edit this file by hand.</p>
${cards}
  </div>
</body>
</html>
`;

fs.writeFileSync(dir('preview/coa-banner-preview.html'), html);
console.log(`preview/coa-banner-preview.html — ${products.length} products:`);
products.forEach(p => console.log(`  ${String(p.id).padStart(5)}  ${p.sku.padEnd(19)} ${p.label}`));
